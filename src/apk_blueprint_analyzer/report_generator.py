"""Report generator for APK Blueprint Analyzer.

Assembles all analysis results into structured output files:
- ``report.md`` — Full App Blueprint Report (human-readable)
- ``blueprint.json`` — Structured data (machine-readable)
- ``permissions.md`` — Permission breakdown
- ``components.md`` — Component listing
- ``libraries.md`` — Detected libraries
- ``screens.md`` — Screen/navigation map
- ``risks.md`` — Security and privacy findings

All reports are written to a single output directory.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from apk_blueprint_analyzer import __version__
from apk_blueprint_analyzer.apk_parser import ApkMetadata
from apk_blueprint_analyzer.component_extractor import ComponentInfo
from apk_blueprint_analyzer.library_detector import LibraryMatch
from apk_blueprint_analyzer.manifest_analyzer import ManifestInfo
from apk_blueprint_analyzer.permission_analyzer import PermissionDetail
from apk_blueprint_analyzer.risk_scanner import RiskFinding
from apk_blueprint_analyzer.screen_mapper import ScreenInfo
from apk_blueprint_analyzer.utils import ensure_directory


class AnalysisResult:
    """Aggregated results from all analyzers.

    This is the single data object passed to the report generator.

    Attributes:
        metadata: APK file metadata.
        manifest: Parsed manifest information.
        components: Extracted components.
        permissions: Analyzed permissions.
        libraries: Detected libraries.
        screens: Mapped screens.
        risks: Risk findings.
        timestamp: ISO-8601 timestamp of when the analysis was performed.
    """

    def __init__(
        self,
        metadata: ApkMetadata,
        manifest: ManifestInfo,
        components: list[ComponentInfo],
        permissions: list[PermissionDetail],
        libraries: list[LibraryMatch],
        screens: list[ScreenInfo],
        risks: list[RiskFinding],
    ) -> None:
        self.metadata = metadata
        self.manifest = manifest
        self.components = components
        self.permissions = permissions
        self.libraries = libraries
        self.screens = screens
        self.risks = risks
        self.timestamp = datetime.now(timezone.utc).isoformat()

    def to_dict(self) -> dict[str, Any]:
        """Serialize all results to a nested dictionary."""
        return {
            "tool": "APK Blueprint Analyzer",
            "version": __version__,
            "timestamp": self.timestamp,
            "metadata": self.metadata.to_dict(),
            "manifest": self.manifest.to_dict(),
            "components": [c.to_dict() for c in self.components],
            "permissions": [p.to_dict() for p in self.permissions],
            "libraries": [lib.to_dict() for lib in self.libraries],
            "screens": [s.to_dict() for s in self.screens],
            "risks": [r.to_dict() for r in self.risks],
        }


class ReportGenerator:
    """Generates output reports from analysis results.

    Writes all report files to the specified output directory.

    Args:
        result: The aggregated :class:`AnalysisResult`.
        output_dir: Directory to write reports into.
    """

    def __init__(self, result: AnalysisResult, output_dir: str | Path) -> None:
        self._result = result
        self._output_dir = Path(output_dir)

    def generate_all(self) -> Path:
        """Generate all report files.

        Returns:
            Path to the output directory containing the reports.
        """
        ensure_directory(self._output_dir)

        self._write_blueprint_json()
        self._write_report_md()
        self._write_permissions_md()
        self._write_components_md()
        self._write_libraries_md()
        self._write_screens_md()
        self._write_risks_md()

        return self._output_dir

    def _write_file(self, filename: str, content: str) -> Path:
        """Write content to a file in the output directory."""
        path = self._output_dir / filename
        path.write_text(content, encoding="utf-8")
        return path

    # ── JSON Blueprint ───────────────────────────────────────────────

    def _write_blueprint_json(self) -> None:
        """Write the structured blueprint.json file."""
        data = self._result.to_dict()
        content = json.dumps(data, indent=2, ensure_ascii=False)
        self._write_file("blueprint.json", content)

    # ── Main Report ──────────────────────────────────────────────────

    def _write_report_md(self) -> None:
        """Write the full report.md file."""
        r = self._result
        lines: list[str] = []
        lines.append(f"# App Blueprint Report: {r.manifest.package_name}")
        lines.append("")
        lines.append(f"> Generated by APK Blueprint Analyzer v{__version__}")
        lines.append(f"> Timestamp: {r.timestamp}")
        lines.append("")
        lines.append("---")
        lines.append("")

        # ── Overview ──
        lines.append("## Overview")
        lines.append("")
        lines.append("| Property | Value |")
        lines.append("|---|---|")
        lines.append(f"| **Package** | `{r.manifest.package_name}` |")
        lines.append(
            f"| **Version** | {r.manifest.version_name or 'N/A'} "
            f"(code: {r.manifest.version_code or 'N/A'}) |"
        )
        lines.append(f"| **Min SDK** | {r.manifest.min_sdk or 'N/A'} |")
        lines.append(f"| **Target SDK** | {r.manifest.target_sdk or 'N/A'} |")
        lines.append(f"| **File Size** | {r.metadata.file_size_human} |")
        lines.append(f"| **SHA-256** | `{r.metadata.sha256[:16]}...` |")
        lines.append(f"| **Files in APK** | {r.metadata.entry_count} |")
        lines.append(f"| **DEX Files** | {r.metadata.dex_count} |")
        lines.append("")

        # ── Component Summary ──
        lines.append("## Components Summary")
        lines.append("")
        type_counts: dict[str, int] = {}
        for c in r.components:
            type_counts[c.component_type] = type_counts.get(c.component_type, 0) + 1
        lines.append("| Type | Count |")
        lines.append("|---|---|")
        for ctype in ("activity", "service", "receiver", "provider"):
            lines.append(f"| {ctype.capitalize()}s | {type_counts.get(ctype, 0)} |")
        lines.append("")

        # ── Permission Summary ──
        lines.append("## Permissions Summary")
        lines.append("")
        lines.append(f"Total permissions requested: **{len(r.permissions)}**")
        lines.append("")
        dangerous = [
            p for p in r.permissions if p.protection_level.value == "dangerous"
        ]
        if dangerous:
            lines.append(
                f"⚠️ **{len(dangerous)} dangerous permission(s)** "
                "require runtime approval."
            )
        lines.append("")

        # ── Libraries Summary ──
        lines.append("## Libraries Detected")
        lines.append("")
        lines.append(f"Total: **{len(r.libraries)}** recognized libraries/SDKs.")
        lines.append("")

        # ── Risk Summary ──
        lines.append("## Risk Summary")
        lines.append("")
        if r.risks:
            lines.append(f"Total findings: **{len(r.risks)}**")
            lines.append("")
            for risk in r.risks:
                icon = {
                    "critical": "🔴",
                    "high": "🟠",
                    "medium": "🟡",
                    "low": "🔵",
                    "info": "ℹ️",
                }.get(risk.severity.value, "")
                lines.append(
                    f"- {icon} **[{risk.severity.value.upper()}]** {risk.title}"
                )
        else:
            lines.append("✅ No significant risks detected.")
        lines.append("")

        lines.append("---")
        lines.append("")
        lines.append("*See individual report files for detailed breakdowns.*")
        lines.append("")

        self._write_file("report.md", "\n".join(lines))

    # ── Permissions ──────────────────────────────────────────────────

    def _write_permissions_md(self) -> None:
        """Write the permissions.md file."""
        r = self._result
        lines: list[str] = []
        lines.append("# Permissions Analysis")
        lines.append("")
        lines.append(f"Package: `{r.manifest.package_name}`")
        lines.append("")

        if not r.permissions:
            lines.append("No permissions declared.")
        else:
            lines.append("## Requested Permissions")
            lines.append("")
            lines.append("| Permission | Protection Level | Risk | Purpose |")
            lines.append("|---|---|---|---|")
            for p in r.permissions:
                lines.append(
                    f"| `{p.name}` | {p.protection_level.value} | "
                    f"{p.risk_category.value} | {p.description} |"
                )
        lines.append("")

        if r.manifest.permissions_defined:
            lines.append("## Custom Permissions Defined")
            lines.append("")
            for p in r.manifest.permissions_defined:
                lines.append(f"- `{p}`")
            lines.append("")

        self._write_file("permissions.md", "\n".join(lines))

    # ── Components ───────────────────────────────────────────────────

    def _write_components_md(self) -> None:
        """Write the components.md file."""
        r = self._result
        lines: list[str] = []
        lines.append("# Application Components")
        lines.append("")
        lines.append(f"Package: `{r.manifest.package_name}`")
        lines.append("")

        for ctype in ("activity", "service", "receiver", "provider"):
            components = [c for c in r.components if c.component_type == ctype]
            lines.append(f"## {ctype.capitalize()}s ({len(components)})")
            lines.append("")
            if not components:
                lines.append("None declared.")
            else:
                for c in components:
                    exported_str = (
                        "✅ Exported" if c.exported else "🔒 Not exported"
                    )
                    launcher_str = " 🚀 **Launcher**" if c.is_launcher else ""
                    lines.append(f"### `{c.name}`")
                    lines.append(f"- Status: {exported_str}{launcher_str}")
                    if c.permission:
                        lines.append(f"- Required permission: `{c.permission}`")
                    if c.intent_filters:
                        lines.append("- Intent filters:")
                        for filt in c.intent_filters:
                            for action in filt.actions:
                                lines.append(f"  - Action: `{action}`")
                            for cat in filt.categories:
                                lines.append(f"  - Category: `{cat}`")
                    lines.append("")
            lines.append("")

        self._write_file("components.md", "\n".join(lines))

    # ── Libraries ────────────────────────────────────────────────────

    def _write_libraries_md(self) -> None:
        """Write the libraries.md file."""
        r = self._result
        lines: list[str] = []
        lines.append("# Detected Libraries & SDKs")
        lines.append("")
        lines.append(f"Package: `{r.manifest.package_name}`")
        lines.append("")

        if not r.libraries:
            lines.append("No recognized libraries detected.")
        else:
            lines.append("| Library | Category | Privacy Relevant | Description |")
            lines.append("|---|---|---|---|")
            for lib in r.libraries:
                privacy = "⚠️ Yes" if lib.privacy_relevant else "No"
                lines.append(
                    f"| **{lib.name}** | {lib.category} | {privacy} | "
                    f"{lib.description} |"
                )
        lines.append("")

        privacy_libs = [lib for lib in r.libraries if lib.privacy_relevant]
        if privacy_libs:
            lines.append("## Privacy-Relevant SDKs")
            lines.append("")
            lines.append(
                "The following SDKs may collect or transmit user data. "
                "Review their data practices:"
            )
            lines.append("")
            for lib in privacy_libs:
                lines.append(f"- **{lib.name}** — {lib.description}")
            lines.append("")

        self._write_file("libraries.md", "\n".join(lines))

    # ── Screens ──────────────────────────────────────────────────────

    def _write_screens_md(self) -> None:
        """Write the screens.md file."""
        r = self._result
        lines: list[str] = []
        lines.append("# Screen & Navigation Map")
        lines.append("")
        lines.append(f"Package: `{r.manifest.package_name}`")
        lines.append(f"Total screens: **{len(r.screens)}**")
        lines.append("")

        if not r.screens:
            lines.append("No activities found to map.")
        else:
            for screen in r.screens:
                launcher_str = (
                    " 🚀 **Entry Point**" if screen.is_launcher else ""
                )
                lines.append(f"## {screen.short_name}{launcher_str}")
                lines.append("")
                lines.append(f"- Full name: `{screen.activity_name}`")
                lines.append(f"- Purpose: {screen.inferred_purpose}")
                if screen.is_exported:
                    lines.append("- Exported: ✅ Yes")
                if screen.deeplink_schemes:
                    schemes = ", ".join(
                        f"`{s}`" for s in screen.deeplink_schemes
                    )
                    lines.append(f"- Deep link schemes: {schemes}")
                if screen.deeplink_hosts:
                    hosts = ", ".join(f"`{h}`" for h in screen.deeplink_hosts)
                    lines.append(f"- Deep link hosts: {hosts}")
                if screen.layout_files:
                    lines.append("- Associated layouts:")
                    for layout in screen.layout_files:
                        lines.append(f"  - `{layout}`")
                lines.append("")

        self._write_file("screens.md", "\n".join(lines))

    # ── Risks ────────────────────────────────────────────────────────

    def _write_risks_md(self) -> None:
        """Write the risks.md file."""
        r = self._result
        lines: list[str] = []
        lines.append("# Security & Privacy Risk Assessment")
        lines.append("")
        lines.append(f"Package: `{r.manifest.package_name}`")
        lines.append("")
        lines.append(
            "> ⚠️ This is a heuristic-based assessment. Findings should be "
            "reviewed by a qualified security professional."
        )
        lines.append("")

        if not r.risks:
            lines.append("✅ **No significant risks detected.**")
        else:
            severity_icons = {
                "critical": "🔴",
                "high": "🟠",
                "medium": "🟡",
                "low": "🔵",
                "info": "ℹ️",
            }

            # Summary table.
            lines.append("## Summary")
            lines.append("")
            lines.append("| Severity | Count |")
            lines.append("|---|---|")
            for sev in ("critical", "high", "medium", "low", "info"):
                count = sum(1 for f in r.risks if f.severity.value == sev)
                if count > 0:
                    lines.append(
                        f"| {severity_icons.get(sev, '')} {sev.upper()} | {count} |"
                    )
            lines.append("")

            # Detailed findings.
            lines.append("## Findings")
            lines.append("")
            for i, risk in enumerate(r.risks, 1):
                icon = severity_icons.get(risk.severity.value, "")
                lines.append(f"### {i}. {icon} {risk.title}")
                lines.append("")
                lines.append(f"**Severity:** {risk.severity.value.upper()}")
                lines.append(f"**Category:** {risk.category}")
                lines.append("")
                lines.append(risk.description)
                lines.append("")
                if risk.recommendation:
                    lines.append(
                        f"**Recommendation:** {risk.recommendation}"
                    )
                    lines.append("")
                if risk.evidence:
                    lines.append("**Evidence:**")
                    for ev in risk.evidence:
                        lines.append(f"- `{ev}`")
                    lines.append("")

        self._write_file("risks.md", "\n".join(lines))
